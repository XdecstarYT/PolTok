// Generates src/data/au-fed2025.ts: 2025 federal election House results by division from the AEC
// (Tally Room downloads, event 31496, Final Results):
//   HouseFirstPrefsByCandidateByVoteTypeDownload-31496.csv  (first preferences)
//   HouseTcpByCandidateByVoteTypeDownload-31496.csv         (two-candidate-preferred)
//   HouseTppByDivisionDownload-31496.csv                    (Labor v Coalition two-party-preferred)
// https://results.aec.gov.au/31496/Website/HouseDownloadsMenu-31496-Csv.htm — © Commonwealth of Australia (AEC), CC BY 4.0.
// Run: node scripts/gen-au-fed2025.mjs [cacheDir]
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const CACHE = process.argv[2] || join(tmpdir(), 'poltok-aec');
mkdirSync(CACHE, { recursive: true });
const B = 'https://results.aec.gov.au/31496/Website/Downloads/';

async function csv(name) {
  const f = join(CACHE, name);
  if (!existsSync(f)) {
    const r = await fetch(B + name);
    if (!r.ok) throw new Error(name + ' ' + r.status);
    writeFileSync(f, Buffer.from(await r.arrayBuffer()));
  }
  const lines = readFileSync(f, 'utf8').split(/\r?\n/).slice(1).filter(Boolean);
  const split = (l) => { const o = []; let c = '', q = false; for (const ch of l) { if (ch === '"') q = !q; else if (ch === ',' && !q) { o.push(c); c = ''; } else c += ch; } o.push(c); return o; };
  const head = split(lines.shift());
  return lines.map((l) => Object.fromEntries(split(l).map((v, i) => [head[i], v])));
}

// Map AEC party abbreviations onto PolTok party codes (src/data/au.ts AU_PARTIES).
const PMAP = { ALP: 'ALP', LP: 'LIB', LNP: 'LNP', NP: 'NAT', CLP: 'LIB', GRN: 'GRN', GVIC: 'GRN', ON: 'ONP', IND: 'IND', KAP: 'KAP', XEN: 'CA', CYA: 'TOP', JLN: 'JLN', FFP: 'FF', LTP: 'LDP', AJP: 'AJP', HMP: 'LCV', GRPF: 'PF', VNS: 'VS' };
const code = (ab, nm) => PMAP[ab] ?? (/independent/i.test(nm) || !ab ? 'IND' : 'OTH');
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const fp = await csv('HouseFirstPrefsByCandidateByVoteTypeDownload-31496.csv');
const tcp = await csv('HouseTcpByCandidateByVoteTypeDownload-31496.csv');
const tpp = await csv('HouseTppByDivisionDownload-31496.csv');

const out = {};
for (const r of fp) {
  if (r.Surname === 'Informal' || !r.DivisionNm) continue;
  const d = (out[slug(r.DivisionNm)] ??= { fp: [], tcp: [], tpp: null, formal: 0 });
  const v = +r.TotalVotes;
  d.formal += v;
  d.fp.push({ n: `${r.GivenNm} ${r.Surname}`.trim(), p: code(r.PartyAb, r.PartyNm), ab: r.PartyAb, v, sw: r.Swing === '' ? null : +r.Swing, el: r.Elected === 'Y' });
}
for (const [id, d] of Object.entries(out)) {
  d.fp.sort((a, b) => b.v - a.v);
  for (const c of d.fp) c.pct = Math.round((1000 * c.v) / d.formal) / 10;
  d.fp = d.fp.map(({ n, p, ab, v, pct, sw, el }) => ({ n, p, ab, v, pct, sw, ...(el ? { el: true } : {}) }));
  out[id] = d;
}
const tcpTot = {};
for (const r of tcp) { const id = slug(r.DivisionNm); tcpTot[id] = (tcpTot[id] ?? 0) + +r.TotalVotes; }
for (const r of tcp) {
  const id = slug(r.DivisionNm);
  out[id].tcp.push({ n: `${r.GivenNm} ${r.Surname}`, p: code(r.PartyAb, r.PartyNm), v: +r.TotalVotes, pct: Math.round((10000 * +r.TotalVotes) / tcpTot[id]) / 100, sw: r.Swing === '' ? null : +r.Swing, ...(r.Elected === 'Y' ? { el: true } : {}) });
}
for (const r of tpp) {
  const id = slug(r.DivisionNm);
  out[id].tpp = { alp: +r['Australian Labor Party Percentage'], lnp: +r['Liberal/National Coalition Percentage'], sw: +r.Swing };
}

const au = readFileSync(new URL('../src/data/au.ts', import.meta.url), 'utf8');
const fedIds = [...au.matchAll(/"id": "([a-z0-9-]+)"[^}]*"chamber": "federal"/g)].map((m) => m[1]);
const miss = fedIds.filter((i) => !out[i]);
const extra = Object.keys(out).filter((i) => !fedIds.includes(i));
const badTcp = Object.entries(out).filter(([, d]) => d.tcp.length !== 2).map(([k]) => k);
console.log(`divisions ${Object.keys(out).length}; au.ts ids ${fedIds.length}; missing ${miss}; extra ${extra}; bad tcp ${badTcp}`);
if (miss.length || extra.length || badTcp.length) process.exit(1);

// national primary totals by party code
const nat = {};
let natT = 0;
for (const d of Object.values(out)) for (const c of d.fp) { nat[c.p] = (nat[c.p] ?? 0) + c.v; natT += c.v; }
const natPct = Object.fromEntries(Object.entries(nat).sort((a, b) => b[1] - a[1]).map(([k, v]) => [k, Math.round((1000 * v) / natT) / 10]));
console.log('national primaries', natPct);

writeFileSync(new URL('../src/data/au-fed2025.ts', import.meta.url), `// GENERATED by scripts/gen-au-fed2025.mjs — do not hand-edit.
// Source: Australian Electoral Commission, 2025 federal election (event 31496) Final Results downloads,
// https://results.aec.gov.au/31496/Website/HouseDownloadsMenu-31496-Csv.htm — © Commonwealth of Australia, CC BY 4.0.
// fp = first preferences (pct of formal votes, sw = swing pp); tcp = two-candidate-preferred; tpp = ALP v Coalition 2PP (%).
// Party codes: CLP folded into LIB; TOP = Trumpet of Patriots; FF = Family First; LDP = Libertarians; LCV = Legalise Cannabis.
export interface Fed25Cand { n: string; p: string; ab?: string; v: number; pct: number; sw: number | null; el?: boolean }
export interface Fed25Div { fp: Fed25Cand[]; tcp: Fed25Cand[]; tpp: { alp: number; lnp: number; sw: number } | null; formal: number }
export const FED2025_SOURCE = 'https://results.aec.gov.au/31496/Website/HouseDownloadsMenu-31496-Csv.htm';
export const FED2025_NATIONAL_PRIMARY: Record<string, number> = ${JSON.stringify(natPct)};
export const FED2025: Record<string, Fed25Div> = ${JSON.stringify(out)};
`);
console.log('wrote src/data/au-fed2025.ts');
