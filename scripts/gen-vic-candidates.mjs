#!/usr/bin/env node
// Generate src/data/vic-candidates.ts: final 2026 Victorian Legislative Assembly candidates, per district, in ballot-paper
// order, from the Victorian Electoral Commission "Find candidates" pages.
// PRIVACY: the VEC pages also list contact names, phone numbers and emails. Those are deliberately NOT read or stored —
// only the candidate's name (as printed on the ballot), their registered party (or none) and ballot position.
// Usage: node scripts/gen-vic-candidates.mjs
import fs from 'node:fs';

const BASE = 'https://www.vec.vic.gov.au';
const INDEX = BASE + '/voting/2026-state-election/find-candidates';
const UA = { 'user-agent': 'Mozilla/5.0 (PolTok data generator; +https://poltok.netlify.app)' };
const PARTY = [
  [/labor/i, 'ALP'], [/liberal(?! democrat)/i, 'LIB'], [/national/i, 'NAT'], [/greens/i, 'GRN'], [/one nation/i, 'ONP'],
  [/family first/i, 'FF'], [/socialist/i, 'VS'], [/libertarian/i, 'LBT'], [/animal justice/i, 'AJP'], [/legalise cannabis/i, 'LCV'],
  [/sustainable australia/i, 'SAP'], [/shooters/i, 'SFF'], [/democratic labour/i, 'DLP'], [/fusion/i, 'FUS'], [/reason/i, 'RSN'],
  [/health australia/i, 'HAP'], [/freedom/i, 'FP'], [/justice/i, 'JP'], [/companions|pets/i, 'APP'], [/victorian community/i, 'VCP'],
];
const code = (p) => (p ? (PARTY.find(([re]) => re.test(p))?.[1] ?? p.split(/\s+/).filter((w) => /^[A-Z]/.test(w)).map((w) => w[0]).join('').slice(0, 4).toUpperCase()) : 'IND');
const tidy = (s) => s.replace(/&#39;|&#x27;/g, "'").replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
const nameOf = (raw) => { // "CARROLL, Ben" → "Ben Carroll"
  const [sur, given] = tidy(raw).split(/,\s*/);
  const cap = (w) => w.toLowerCase().replace(/(^|[\s'-])(\p{L})/gu, (m, a, b) => a + b.toUpperCase()).replace(/\bMc(\p{L})/gu, (m, c) => 'Mc' + c.toUpperCase());
  return given ? `${given.trim()} ${cap(sur)}` : cap(sur);
};

async function get(url) {
  for (let i = 0; i < 3; i++) {
    try { const r = await fetch(url, { headers: UA, signal: AbortSignal.timeout(20000) }); if (r.ok) return r.text(); } catch {}
    await new Promise((r) => setTimeout(r, 1500 * (i + 1)));
  }
  throw new Error('fetch failed: ' + url);
}

const index = await get(INDEX);
const links = [...new Set([...index.matchAll(/href="(\/electoral-boundaries\/state-districts\/([a-z0-9-]+)-district\/nominations)"/g)].map((m) => m[1]))];
if (links.length !== 88) throw new Error(`expected 88 district links, got ${links.length}`);
const districts = {};
const parties = new Map();
for (const href of links) {
  const slug = href.match(/state-districts\/([a-z0-9-]+)-district/)[1];
  const html = await get(BASE + href);
  const tbody = html.split('<tbody>')[1]?.split('</tbody>')[0] ?? '';
  const rows = [...tbody.matchAll(/<tr class="candidate-row">\s*<td>([\s\S]*?)<\/td>/g)].map((m) => m[1]); // first cell only: name + party
  const list = rows.map((cell, i) => {
    const party = tidy((cell.match(/<p>([\s\S]*?)<\/p>/) || [, ''])[1]);
    const n = nameOf(cell.replace(/<p>[\s\S]*?<\/p>/, '').replace(/<[^>]+>/g, ''));
    const p = code(party);
    if (party) parties.set(p, party);
    return [n, p, i + 1];
  });
  if (!list.length) throw new Error('no candidates parsed for ' + slug);
  districts['vic-' + slug] = list;
  process.stdout.write('.');
}
const total = Object.values(districts).reduce((a, l) => a + l.length, 0);
const asAt = new Date().toISOString().slice(0, 10);
const out = `// GENERATED by scripts/gen-vic-candidates.mjs on ${asAt} — do not hand-edit.
// Final 2026 Victorian Legislative Assembly candidates in ballot-paper order (Victorian Electoral Commission,
// ${INDEX}). Names, registered party and ballot position only; contact details are intentionally not collected.
// ${Object.keys(districts).length} districts, ${total} candidates.
export const VIC_CANDIDATES_2026: { asAt: string; source: string; parties: Record<string, string>; districts: Record<string, [name: string, party: string, ballot: number][]> } = ${JSON.stringify({ asAt, source: INDEX, parties: Object.fromEntries(parties), districts })};
`;
fs.writeFileSync(new URL('../src/data/vic-candidates.ts', import.meta.url), out);
fs.writeFileSync(new URL('../shared/au/vic-candidates-2026.json', import.meta.url), JSON.stringify({ asAt, districts }));
console.log(`\n${Object.keys(districts).length} districts, ${total} candidates, parties:`, Object.fromEntries(parties));
